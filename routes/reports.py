"""
Automated Report Generation Routes
- GET /api/reports/summary — Generate period summary (daily/weekly/monthly)
- GET /api/reports/export — Download summary as PDF
"""

import io
from datetime import datetime, timezone, timedelta
from fastapi import APIRouter, Depends, Query, Response
from backend.database.connection import get_database
from backend.middleware.auth import get_current_user
from backend.services.risk_engine import predict_threat_trend
from backend.services.threat_monitor import log_security_event

router = APIRouter(prefix="/reports", tags=["reports"])

PERIOD_HOURS = {
    "daily": 24,
    "weekly": 168,
    "monthly": 720,
}


async def _generate_summary(period: str) -> dict:
    """Generate a comprehensive summary report for a given period."""
    db = get_database()
    hours = PERIOD_HOURS.get(period, 24)
    cutoff = datetime.now(timezone.utc) - timedelta(hours=hours)

    # Scan stats
    all_scans_cursor = db.scans.find({})
    all_scans = await all_scans_cursor.to_list(1000)

    # Filter by period (scan_time might be string or datetime)
    period_scans = []
    for s in all_scans:
        st = s.get("scan_time")
        if isinstance(st, str):
            try:
                st = datetime.fromisoformat(st)
            except Exception:
                continue
        if isinstance(st, datetime):
            if st.tzinfo is None:
                st = st.replace(tzinfo=timezone.utc)
            if st >= cutoff:
                period_scans.append(s)

    total_scans = len(period_scans)
    phishing_count = sum(1 for s in period_scans if s.get("prediction") == "PHISHING")
    benign_count = total_scans - phishing_count
    avg_risk = (
        round(sum(s.get("risk_score", 0) for s in period_scans) / total_scans, 1)
        if total_scans > 0 else 0
    )

    # Top threats (highest risk)
    sorted_scans = sorted(period_scans, key=lambda x: x.get("risk_score", 0), reverse=True)
    top_threats = []
    for s in sorted_scans[:10]:
        top_threats.append({
            "url": s.get("url", ""),
            "prediction": s.get("prediction", ""),
            "risk_score": s.get("risk_score", 0),
            "scan_time": (
                s.get("scan_time").isoformat()
                if isinstance(s.get("scan_time"), datetime)
                else str(s.get("scan_time", ""))
            ),
        })

    # User stats
    total_users = await db.users.count_documents({})

    # Incident stats
    incidents_cursor = db.incidents.find({})
    all_incidents = await incidents_cursor.to_list(500)
    period_incidents = []
    for inc in all_incidents:
        ct = inc.get("created_at")
        if isinstance(ct, str):
            try:
                ct = datetime.fromisoformat(ct)
            except Exception:
                continue
        if isinstance(ct, datetime):
            if ct.tzinfo is None:
                ct = ct.replace(tzinfo=timezone.utc)
            if ct >= cutoff:
                period_incidents.append(inc)

    open_incidents = sum(1 for i in period_incidents if i.get("status") == "open")
    resolved_incidents = sum(1 for i in period_incidents if i.get("status") == "resolved")

    # Threat trend
    trend = await predict_threat_trend(hours)

    return {
        "period": period,
        "period_hours": hours,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "scan_summary": {
            "total_scans": total_scans,
            "phishing_detected": phishing_count,
            "benign_detected": benign_count,
            "detection_rate": round(phishing_count / total_scans * 100, 1) if total_scans > 0 else 0,
            "avg_risk_score": avg_risk,
        },
        "top_threats": top_threats,
        "incident_summary": {
            "total_incidents": len(period_incidents),
            "open": open_incidents,
            "resolved": resolved_incidents,
        },
        "user_stats": {
            "total_users": total_users,
        },
        "threat_trend": {
            "direction": trend.get("trend", "stable"),
            "prediction": trend.get("prediction", ""),
            "avg_risk": trend.get("avg_risk", 0),
        },
    }


@router.get("/summary")
async def get_report_summary(
    period: str = Query("daily", regex="^(daily|weekly|monthly)$"),
    current_user: dict = Depends(get_current_user)
):
    """Generate a comprehensive summary report."""
    summary = await _generate_summary(period)

    await log_security_event(
        event_type="report_generated",
        description=f"{period.capitalize()} summary report generated by {current_user.get('email', '')}",
        user_id=str(current_user.get('_id', '')),
        username=current_user.get('email', ''),
        source_module="report_engine",
    )

    return summary


@router.get("/export")
async def export_report_pdf(
    period: str = Query("daily", regex="^(daily|weekly|monthly)$"),
    current_user: dict = Depends(get_current_user)
):
    """Export summary report as PDF."""
    summary = await _generate_summary(period)

    # Build a simple text-based PDF using reportlab-style approach
    # For simplicity, we generate a structured text report
    from backend.utils.pdf_generator import generate_report_summary_pdf
    pdf_bytes = generate_report_summary_pdf(summary)

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f"attachment; filename=aegis_x_{period}_report.pdf"
        }
    )
